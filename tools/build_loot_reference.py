"""Build an offline Classic reference, never character observations.

Input: cmangos/classic-db Full_DB/ClassicDB_1_12_1_z2815.sql.gz.
Raw SQL is parsed as data, not executed. Group/reference probabilities that
depend on conditions, repeat rolls, or duplicate items remain unknown.
"""
import gzip
import hashlib
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'tools/data-cache'
blob = (CACHE / 'classic.sql.gz').read_bytes()
assert hashlib.sha1(b'blob ' + str(len(blob)).encode() + b'\0' + blob).hexdigest() == '0a77f5230a3d5d6db968678203dfe3b30c34b8a9', 'Unexpected source revision'
sql = gzip.decompress(blob).decode('utf8')
token = re.compile(r"'(?:\\.|[^'\\])*'|NULL|-?\d+(?:\.\d+)?")
row_pattern = re.compile(r"\(((?:'(?:\\.|[^'\\])*'|[^'()])*)\)")

def rows(table):
    for line in sql.splitlines():
        if not line.startswith('INSERT INTO `' + table + '` VALUES '):
            continue
        for match in row_pattern.finditer(line):
            result = []
            for value in token.findall(match[1]):
                if value.startswith("'"):
                    result.append(re.sub(r'\\(.)', r'\1', value[1:-1]))
                elif value == 'NULL':
                    result.append(None)
                else:
                    result.append(float(value) if '.' in value else int(value))
            yield result

def lua(value):
    if value is None:
        return 'false'
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return str(value)

output = ['-- Generated by tools/build_loot_reference.py. Data: cMaNGOS Classic DB, GPL-3.0.',
          '-- Classic reference only; NOT verified Forever drop probabilities.',
          'local _, A = ...', 'A.LootReference = {creatures={}, loot={}, refs={}, names={}}',
          'local D = A.LootReference']
names = {}
for table, field in [('creature_loot_template', 'loot'), ('reference_loot_template', 'refs')]:
    groups = defaultdict(list)
    for entry, item, chance, group, minimum, maximum, condition, comment in rows(table):
        groups[entry].append([item, chance, group, minimum, maximum, condition])
        if minimum > 0 and comment:
            names[item] = comment
    for entry, values in sorted(groups.items()):
        output.append('D.' + field + '[' + str(entry) + ']={' + ','.join('{' + ','.join(map(lua, row)) + '}' for row in values) + '}')

schema = re.search(r'CREATE TABLE `creature_template` \((.*?)\n\)', sql, re.S)[1]
columns = re.findall(r'^  `([^`]+)`', schema, re.M)
count = 0
portraits = ['-- cMaNGOS Classic display IDs; see REFERENCE-SOURCES.txt.', 'local _, A = ...', 'A.PortraitDisplays = {']
for row in rows('creature_template'):
    creature = dict(zip(columns, row))
    display = next((creature['ModelId' + str(i)] for i in range(1, 5) if creature['ModelId' + str(i)]), None)
    if display:
        portraits.append('[' + str(creature['Entry']) + ']=' + str(display) + ',')
    if not creature['LootId']:
        continue
    values = [creature['LootId'], creature['Name'], creature['MinLevel'], creature['MaxLevel']]
    output.append('D.creatures[' + str(creature['Entry']) + ']={' + ','.join(map(lua, values)) + '}')
    count += 1
for item, name in sorted(names.items()):
    output.append('D.names[' + str(item) + ']=' + lua(name))
(ROOT / 'RaynnaTracker/LootReference.lua').write_text('\n'.join(output) + '\n', encoding='utf8')
portraits.append('}')
(ROOT / 'RaynnaTracker/PortraitDisplays.lua').write_text('\n'.join(portraits) + '\n', encoding='utf8')
print(f'Generated Classic reference: {count} creatures, {len(names)} named items')
